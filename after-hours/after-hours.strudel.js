// ───────────── 乐器 ─────────────
// 音符写成 "eb4:0.8" = 音高 eb4、力度 0.8（轨内相对力度，来自 MIDI velocity；不写就是 1）
// Strudel 会把冒号后的数字放进 n，这里把它挪到 velocity，免得被当成采样编号
const vel = ({ n, ...v }) => (n === undefined ? v : { ...v, velocity: n });

// Grand Piano (Classic) — 钢琴脉冲/和弦
const pulse = p => note(p).fmap(vel).sound("piano").gain(.5).release(.12);
