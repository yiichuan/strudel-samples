// Acoustic Gtr (Classic) — 原声吉他
const acgtr = p => note(p).fmap(vel).sound("gm_acoustic_guitar_steel").gain(.45);
// Synth Pluck (Classic) — 合成拨弦
const pluck = p => note(p).fmap(vel).sound("sawtooth").lpf(2400).decay(.15).sustain(0).gain(.4);
// Strings — 弦乐
const strings = p => note(p).fmap(vel).sound("gm_string_ensemble_1").gain(.55);
// Bass Guitar — 电贝斯
const bassgtr = p => note(p).fmap(vel).sound("gm_electric_bass_finger").gain(.8);
// Pop Synth — 合成低音
const popsynth = p => note(p).fmap(vel).sound("supersaw").lpf(900).gain(.4).release(.5);
// 8-Bit Sine — 8-bit 正弦
const bitsine = p => note(p).fmap(vel).sound("sine").crush(6).gain(.35).release(.15);
// Sitar — 西塔琴
const sitar = p => note(p).fmap(vel).sound("gm_sitar").gain(.5);
// Distortion Guitar — 失真吉他
const distgtr = p => note(p).fmap(vel).sound("gm_distortion_guitar").gain(.35);
// 909 Drum Kit — 909 鼓组（鼓映射：36→bd, 38→sd, 42→hh, 49→cr）
